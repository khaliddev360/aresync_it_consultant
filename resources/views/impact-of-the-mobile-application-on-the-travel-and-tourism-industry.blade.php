                                    <p><strong>Apps for travel and tourism: some unknown facts</strong></p>
                                    <ul>
                                        <li>Travel and tourism apps are used by over 85% of the population when they are relaxing at any time of day.</li>
                                        <li>In 30% of cases, users use the app to compare combined offers like flight and hotel bookings.</li>
                                        <li>The app is used by 15% of users to plan upcoming trips.</li>
                                        <li>There are 7 most downloaded apps in the category Travel &amp; Tourism.</li>
                                        <li>The app is downloaded just before a vacation by 15% of users.</li>
                                        <li>Travel and tourism apps are now designed by Android App Developers.</li>
                                    </ul>
                                    <p><strong>Different purposes for using the Tourism &amp; Travel apps</strong></p>
                                    <ul>
                                        <li>Locating tourist spots/recreation zones using a map &#8211; 49.1%</li>
                                        <li>62.1% of people search for nearby restaurants</li>
                                        <li>In 48.1% of cases, GPS navigation is used</li>
                                        <li>46% of hotel bookings are online</li>
                                        <li>Combinations of offers (joining offers) &#8211; 33.3%</li>
                                        <li>Setting a reminder for boarding notifications &#8211; Tickets purchased &#8211; 8.1%</li>
